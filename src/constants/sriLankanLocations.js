// Flatten all locations and remove duplicates
const allLocationsRaw = sriLankanLocations.flatMap(province => province.locations);

// Remove duplicates while preserving order
export const allLocations = [...new Set(allLocationsRaw)];

// Export province data for advanced filtering
export const getLocationsByProvince = (provinceName) => {
    const province = sriLankanLocations.find(p => p.province === provinceName);
    return province ? province.locations : [];
};

// Export all provinces
export const allProvinces = sriLankanLocations.map(p => p.province);

// Search locations by name (case-insensitive)
export const searchLocations = (query) => {
    if (!query || query.trim() === '') return allLocations;
    
    const searchTerm = query.toLowerCase().trim();
    return allLocations.filter(location => 
        location.toLowerCase().includes(searchTerm)
    );
};